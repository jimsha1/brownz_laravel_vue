<?php

namespace App\Repositories;

use App\Repositories\Base\BaseRepository;
use Illuminate\Support\Facades\DB;
use VocomiApp\Libraries\Exception\VocoQueryException;

class AutoIncrementMasterRepository extends BaseRepository
{
    public function __construct(\App\Models\AutoIncrementMaster $model)
    {
        parent::__construct($model);
    }

    /**
     * DO NOT CALL THIS FUNCTION FROM OUTSIDE ANY "DB TRANSACTION"
     *
     * @param int $auto_increment_id auto increment type id
     * @param string $prefix
     * @return string unique reference code
     * @throws VocoQueryException
     */
    public static function getNextReferenceCode($auto_increment_id, $prefix = false)
    {
        // get PDO instance
        $connection = DB::getPdo();

        if ($connection instanceof \PDO && true !== $connection->inTransaction()) {
            throw new VocoQueryException('Database transaction not yet initiated');
        }

        $auto_increment_info = \App\Models\AutoIncrementMaster::find($auto_increment_id);

        if (null === $auto_increment_info) {
            throw new VocoQueryException('Increment type for reference number not defined');
        }

        $sql = "UPDATE `" . DB::getTablePrefix() . "auto_increment_masters`"
                . " SET `auto_increment_general_value` = CASE"
                . " WHEN (`max_increment_value` = 0)"
                . "   THEN (LAST_INSERT_ID(`auto_increment_general_value`) + 1)"
                . " WHEN (`max_increment_value` <= `auto_increment_general_value`)"
                . "   THEN (LAST_INSERT_ID(`auto_increment_general_value`) - `auto_increment_general_value` + 1)"
                . " ELSE (LAST_INSERT_ID(`auto_increment_general_value` % `max_increment_value`) + 1)"
                . " END"
                . " WHERE `auto_increment_id` = ?";

        DB::statement($sql, [$auto_increment_info->auto_increment_id]);

        // get autogenerated number as LAST_INSERT_ID()
        $auto_increment_number = DB::getPdo()->lastInsertId();

        if (empty($auto_increment_number)) {
            throw new VocoQueryException('Could not generate reference number');
        }

        if (empty($prefix)) {
            $prefix = ($auto_increment_info->use_master_prefix == 1) ? $auto_increment_info->auto_prefix : '';
        }

        return empty($prefix) ?
                $auto_increment_number :
                $prefix . str_pad($auto_increment_number, 3, '0', STR_PAD_LEFT);
    }
}
